CREATE TABLE IF NOT EXISTS `users` (
  `id` varchar(36) NOT NULL,
  `zernio_api_key` varchar(255) NOT NULL,
  `email` varchar(255),
  `display_name` varchar(255),
  `is_active` boolean NOT NULL DEFAULT true,
  `created_at` timestamp NOT NULL DEFAULT (now()),
  `updated_at` timestamp NOT NULL DEFAULT (now()) ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `users_zernio_api_key_unique` (`zernio_api_key`),
  KEY `users_zernio_key_idx` (`zernio_api_key`),
  KEY `users_email_idx` (`email`)
);

CREATE TABLE IF NOT EXISTS `workspaces` (
  `id` varchar(36) NOT NULL,
  `owner_id` varchar(36) NOT NULL,
  `zernio_profile_id` varchar(255),
  `name` varchar(255) NOT NULL,
  `timezone` varchar(100) NOT NULL DEFAULT 'UTC',
  `is_default` boolean NOT NULL DEFAULT false,
  `created_at` timestamp NOT NULL DEFAULT (now()),
  `updated_at` timestamp NOT NULL DEFAULT (now()) ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `workspaces_owner_idx` (`owner_id`),
  KEY `workspaces_zernio_profile_idx` (`zernio_profile_id`),
  CONSTRAINT `workspaces_owner_id_users_id_fk` FOREIGN KEY (`owner_id`) REFERENCES `users` (`id`) ON DELETE CASCADE
);

