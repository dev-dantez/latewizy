CREATE TABLE IF NOT EXISTS `jobs` (
  `id` varchar(36) NOT NULL,
  `workspace_id` varchar(36) NOT NULL,
  `type` enum('generate-content','generate-calendar','publish-entry','retry-publish','send-approval-request','collect-analytics','autopilot-cycle') NOT NULL,
