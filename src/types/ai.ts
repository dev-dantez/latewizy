/**
 * AI Content Generator Type Definitions
 * 
 * This file contains all TypeScript interfaces and types for the AI Content Generator feature.
 * It defines the core data models for brand profiles, generation preferences, auto-scheduling,
 * content variants, drafts, and external API responses.
 */

import type { Platform, PlatformSpecificData } from "@/lib/late-api";
import type { MediaItem, PlatformPost } from "@/hooks/use-posts";

// ============================================================================
// Brand Configuration
// ============================================================================

/**
 * Brand profile stores brand guidelines, tone, voice, and target audience.
 * Used as context for AI content generation.
 */
export interface BrandProfile {
  brandName: string;
  description: string;
  tone: string; // e.g., "professional", "casual", "witty", "inspirational"
  voice: string; // e.g., "expert but approachable"
  targetAudience: string; // e.g., "small business owners, age 25-45"
  industry: string; // e.g., "SaaS", "fashion", "fitness"
  hashtags: string[]; // brand hashtags to always include
  doList: string[]; // what the brand should do
  dontList: string[]; // what the brand should avoid
  defaultCTA: string; // default call-to-action
}

// ============================================================================
// Generation Preferences
// ============================================================================

/**
 * Generation preferences control AI model settings and output options.
 */
export interface GenerationPrefs {
  defaultModel: "llama-3.3-70b" | "llama-3.1-8b";
  temperature: number; // 0.0 - 1.0, default 0.7
  maxTokens: number; // default 1024
  numVariants: number; // 1-5, default 3
  includeHashtags: boolean; // default true
  includeEmoji: boolean; // default true
  includeCTA: boolean; // default true
}

// ============================================================================
// Auto-Schedule Configuration
// ============================================================================

/**
 * Auto-schedule configuration defines the schedule and content themes for batch generation.
 */
export interface AutoScheduleConfig {
  enabled: boolean;
  frequency: "daily" | "every-other-day" | "weekly" | "custom";
  postsPerWeek: number; // 1-14
  postingTimes: string[]; // ["09:00", "13:00", "17:00"] in user timezone
  contentThemes: ContentTheme[];
  startDate: string; // ISO date string
  endDate?: string; // optional, ISO date string
}

/**
 * Content theme represents a category of content with a weighted distribution.
 */
export interface ContentTheme {
  id: string;
  name: string; // e.g., "Educational Tips", "Industry News", "Behind the Scenes"
  description: string;
  weight: number; // 0.0-1.0, relative frequency (must sum to 1.0 across all themes)
}

// ============================================================================
// Content Variants
// ============================================================================

/**
 * Content variant represents one generated content option.
 */
export interface ContentVariant {
  id: string;
  content: string;
  hashtags: string[];
  imageSuggestion: string; // description of ideal image
  callToAction?: string;
  platformSpecificData?: PlatformSpecificData;
  characterCount: number;
  platformValid: boolean; // true if within platform char limits
  warnings: string[]; // e.g., "Hashtags exceed limit for Twitter"
}

// ============================================================================
// Generated Post Drafts
// ============================================================================

/**
 * Generated post draft represents an AI-generated post ready for review.
 */
export interface GeneratedPostDraft {
  id: string; // UUID
  content: string;
  hashtags: string[];
  mediaItems: MediaItem[];
  platforms: PlatformPost[];
  topic: string;
  source: "manual" | "auto-schedule" | "trending";
  generatedAt: string; // ISO timestamp
  status: "draft" | "approved" | "scheduled" | "discarded";
  scheduledFor?: string; // ISO timestamp, set when approved + scheduled
  brandSnapshot: BrandProfile; // snapshot of brand context used
}

/**
 * Draft scheduled post represents a post generated by auto-scheduling.
 * Always has status "draft" until user approval.
 */
export interface DraftScheduledPost {
  id: string;
  content: string;
  hashtags: string[];
  mediaUrls: MediaItem[];
  platforms: PlatformPost[];
  scheduledFor: string; // ISO string, always in future
  topic: string;
  status: "draft"; // always draft for user review
}

// ============================================================================
// Trending Topics
// ============================================================================

/**
 * Trending topic represents a topic suggestion with content angles.
 */
export interface TrendingTopic {
  id: string;
  topic: string;
  angle: string;
  whyItTrends: string;
  contentIdeas: string[]; // max 5 items
}

// ============================================================================
// Stock Images
// ============================================================================

/**
 * Stock image represents a royalty-free image from an external API.
 */
export interface StockImage {
  id: string;
  url: string;
  previewUrl: string;
  tags: string[];
  width: number;
  height: number;
  source: "pixabay" | "unsplash"; // external provider
}

// ============================================================================
// Platform Constraints
// ============================================================================

/**
 * Platform-specific content limits (character counts, hashtag limits).
 */
export interface PlatformConstraints {
  platform: Platform;
  maxCharacters: number;
  maxHashtags: number;
  supportsHashtags: boolean;
  supportsMedia: boolean;
  supportsVideo: boolean;
}

// ============================================================================
// API Request/Response Types
// ============================================================================

/**
 * Request to generate content variants.
 */
export interface GenerateContentRequest {
  topic: string;
  platform: Platform;
  tone?: string;
  brandContext: BrandProfile;
  contentAngle?: string;
  numVariants?: number; // default 3
}

/**
 * Response from content generation.
 */
export interface GenerateContentResponse {
  variants: ContentVariant[];
}

/**
 * Response from image search.
 */
export interface SearchImagesResponse {
  images: StockImage[];
  total: number;
}

/**
 * Request to generate AI image.
 */
export interface GenerateImageRequest {
  prompt: string;
  width?: number; // default 1024
  height?: number; // default 1024
  model?: "flux" | "turbo"; // default "flux"
}

/**
 * Response from AI image generation.
 */
export interface GenerateImageResponse {
  url: string;
  type: "image";
  width: number;
  height: number;
}

/**
 * Request to get trending topics.
 */
export interface TrendingTopicsRequest {
  niche: string;
  brandContext?: BrandProfile;
}

/**
 * Response from trending topics.
 */
export interface TrendingTopicsResponse {
  topics: TrendingTopic[];
}

/**
 * Request to auto-schedule posts.
 */
export interface AutoScheduleRequest {
  config: AutoScheduleConfig;
  brandContext: BrandProfile;
  platforms: PlatformPost[];
  timezone: string;
}

/**
 * Response from auto-schedule.
 */
export interface AutoScheduleResponse {
  draftPosts: DraftScheduledPost[];
}
